"""Real-weight GPU SPEC smoke on a mathematical fixture, never human speech.

The placeholder Korean string only exercises the manifest contract. It is not
spoken by this signal. STOI on this fixture is not a speech-quality measurement.
"""
import argparse
import json
from pathlib import Path
import tempfile

import numpy as np
import soundfile as sf
import torch

from run_korean_melo_spec import ROOT, execute, save, sha256


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assets', type=Path, required=True)
    parser.add_argument('--device', default='cuda')
    args = parser.parse_args()
    folder = Path(tempfile.mkdtemp(prefix='desktop_mock_fixture_', dir=ROOT / 'runs'))
    sr = 44100
    t = np.arange(sr * 2) / sr
    wave = (.12 * np.sin(2 * np.pi * (180 * t + 65 * t**2)) +
            .03 * np.random.default_rng(52).normal(size=t.size))
    wave *= np.minimum(1, t / .05) * np.minimum(1, (2 - t) / .05)
    sf.write(folder / 'fixture.wav', wave, sr, subtype='PCM_16')
    row = dict(utterance_id='math_fixture_001', speaker_id='nonhuman_fixture',
               input_kind='mock', language='ko', model_speaker='KR', split='test',
               text='수학 신호 계약 검사용 가상 대본입니다.', transcript_verified=True,
               transcript_reference='Placeholder only; no spoken content or listening claim.',
               source='Locally generated chirp plus seeded noise; no human recording.',
               research_use_permitted=True, permission_scope='technical_test_only',
               permission_reference='Mathematical fixture generated by this script.',
               original_path='fixture.wav', original_sha256=sha256(folder / 'fixture.wav'),
               sample_rate=sr)
    save(folder / 'input.json', {'schema_version': 1, 'utterances': [row]})
    save(folder / 'LIMITATIONS.json', {'input_kind': 'mock', 'human_speech': False,
         'spoken_korean': False, 'stoi_interpretation': 'Numerical pipeline check only.',
         'not_measured': ['voice protection efficacy', 'SIM', 'CER', 'finetuning']})
    if args.device == 'cuda':
        torch.cuda.reset_peak_memory_stats()
    output = execute(folder / 'input.json', args.assets, device=args.device,
                     allow_nonhuman=True, iterations=(1, 10))
    save(folder / 'result.json', {'run': str(output)})
    if args.device == 'cuda':
        save(output / 'gpu_memory.json', {'peak_allocated_bytes': torch.cuda.max_memory_allocated(),
             'peak_reserved_bytes': torch.cuda.max_memory_reserved(),
             'scope': '2-second mathematical input; SPEC only, not training',
             'gpu': torch.cuda.get_device_name(), 'torch': torch.__version__})
    print(json.dumps({'fixture': str(folder), 'run': str(output)}))


if __name__ == '__main__':
    main()
